"""Step 3: create the GraphRAG workspace (settings.yaml + input docs) for LM Studio.

GraphRAG talks to the token-counting proxy (:1235), which forwards to LM Studio (:1234).
Prompts are GraphRAG's defaults (generated by `graphrag init`); edit
graphrag_workspace/prompts/* only if you must, and log every change in EXPERIMENT_LOG.md.
"""
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config as C
import yaml

PROXY_BASE = "http://localhost:1235/v1"


def main():
    ws = C.GRAPHRAG_ROOT
    if not (ws / "prompts").exists():
        subprocess.run([sys.executable, "-m", "graphrag", "init", "--root", str(ws),
                        "--model", "gpt-4o-mini", "--embedding", "text-embedding-3-small", "--force"],
                       check=True)
    # fresh input folder
    inp = ws / "input"
    shutil.rmtree(inp, ignore_errors=True)
    inp.mkdir(parents=True)
    n = 0
    for p in sorted(C.CORPUS_DIR.glob("*.txt")):
        shutil.copy(p, inp / p.name)
        n += 1

    llm = {"model_provider": "openai", "model": C.LLM_MODEL, "api_base": PROXY_BASE,
           "api_key": C.LLM_API_KEY, "auth_method": "api_key",
           "call_args": {"temperature": 0.0, "max_tokens": 1024, "seed": 0},
           "retry": {"type": "exponential_backoff"}}
    emb = {"model_provider": "openai", "model": C.EMBED_MODEL, "api_base": PROXY_BASE,
           "api_key": C.LLM_API_KEY, "auth_method": "api_key",
           "retry": {"type": "exponential_backoff"}}

    settings = yaml.safe_load((ws / "settings.yaml").read_text(encoding="utf-8"))
    settings["completion_models"] = {"default_completion_model": llm}
    settings["embedding_models"] = {"default_embedding_model": emb}
    settings["concurrent_requests"] = C.GRAPHRAG_CONCURRENCY
    settings["chunking"] = {"type": "tokens", "size": C.CHUNK_TOKENS, "overlap": C.CHUNK_OVERLAP,
                            "encoding_model": "cl100k_base"}
    settings["extract_graph"]["max_gleanings"] = 0          # small models: keep extraction simple
    settings["extract_graph"]["entity_types"] = ["person", "organization", "geo", "event"]
    settings["community_reports"]["max_length"] = 1200
    settings["vector_store"] = {"type": "lancedb", "db_uri": "output/lancedb"}
    (ws / "settings.yaml").write_text(yaml.safe_dump(settings, sort_keys=False), encoding="utf-8")
    print(f"workspace ready at {ws} with {n} input documents")


if __name__ == "__main__":
    main()
